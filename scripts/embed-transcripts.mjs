// scripts/embed-transcripts.mjs
// Embeds data/transcripts.json (produced offline by
// scripts/fetch-transcripts.ts) into a TS module the server imports
// directly — same reasoning as scripts/embed-widget.mjs: a plain
// fs.readFile at request time isn't reliable in a serverless bundle, so
// the data goes in as a literal at build time instead.
//
// Missing data/transcripts.json (nobody's run the fetch script yet) isn't
// an error — it just embeds an empty dataset, same as if every lookup
// simply found nothing.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const inputPath = path.join(root, "data", "transcripts.json");
const outDir = path.join(root, "src", "generated");
const outPath = path.join(outDir, "transcripts.ts");

let raw = {};
if (fs.existsSync(inputPath)) {
  raw = JSON.parse(fs.readFileSync(inputPath, "utf-8"));
} else {
  console.log(`No ${path.relative(root, inputPath)} yet — embedding an empty transcript dataset.`);
}

// Collapse { videoId: { title, transcript, fetchedAt } } down to just
// { videoId: transcript } for the runtime, and drop entries with no
// transcript (they're kept in the source JSON so fetch-transcripts.ts
// knows not to re-check them, but there's nothing for the server to read).
const transcripts = {};
for (const [videoId, entry] of Object.entries(raw)) {
  if (entry && typeof entry.transcript === "string" && entry.transcript.length > 0) {
    transcripts[videoId] = entry.transcript;
  }
}

const out = `// Auto-generated by scripts/embed-transcripts.mjs from data/transcripts.json — do not edit by hand.
export const TRANSCRIPTS: Record<string, string> = ${JSON.stringify(transcripts, null, 2)};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, out);
console.log(
  `Embedded ${Object.keys(transcripts).length} transcript(s) -> ${path.relative(root, outPath)}`,
);
